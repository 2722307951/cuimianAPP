export function buildHypnoTargetPrompt({
  roleName,
  workName,
  extraInfo,
  extraRules,
}: {
  roleName: string;
  workName: string;
  extraInfo: string;
  extraRules: string;
}): string {
  const name = normalizeText(roleName);
  const sourceWork = normalizeText(workName);
  const supplement = normalizeText(extraInfo) || '无';
  const customRules = normalizeText(extraRules) || '无';
  const baseRules = BASE_ARCHIVE_RULES.replaceAll('{角色名称}', name);

  return `根据当前剧情生成{{User}}将${name}加入催眠对象后的表现。然后开始角色生成，请根据历史记录，以及${name}在作品《${sourceWork}》中的定位和表现，生成符合离线世界的角色档案。可参考以下补充信息：${supplement}

以下为固定生成规则：
${baseRules}

以下为本次额外补充规则：
${customRules}`;
}
